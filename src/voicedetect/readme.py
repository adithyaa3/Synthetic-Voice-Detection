"""Generate the README results block from saved artifacts (no hand-typed numbers).

The block lives between RESULTS_START and RESULTS_END in README.md; `python -m voicedetect.pipeline
readme` rewrites it and tests/test_docs_numbers.py fails if README.md and the artifacts disagree.
"""
from __future__ import annotations

import json

import pandas as pd

from .config import MODEL_LABELS, REPORTS_DIR, ROOT
from .evaluate import SETTING_LABELS

RESULTS_START = "<!-- RESULTS:START (generated by `python -m voicedetect.pipeline readme`; do not edit by hand) -->"
RESULTS_END = "<!-- RESULTS:END -->"
DATA_START = "<!-- DATA:START (generated by `python -m voicedetect.pipeline readme`; do not edit by hand) -->"
DATA_END = "<!-- DATA:END -->"
LABELS = {**MODEL_LABELS, "rbf_svm": "RBF SVM (tuned)", "rbf_svm_original": "RBF SVM (original C=10, gamma=scale)"}


def _j(p):
    return json.loads((REPORTS_DIR / p).read_text(encoding="utf-8"))


def _pm(m, s):
    return f"{m:.3f} ± {s:.3f}"


def _md(df: pd.DataFrame) -> str:
    head = "| " + " | ".join(map(str, df.columns)) + " |\n|" + "---|" * len(df.columns) + "\n"
    return head + "\n".join("| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False))


def results_markdown() -> str:
    meta = json.loads((ROOT / "models" / "metadata.json").read_text(encoding="utf-8"))
    legacy = _j("legacy_reproduction.json")
    sel = _j("selection/model_selection.json")
    aug = _j("selection/augmentation.json")
    cal = _j("selection/calibration.json")
    test = _j("test_metrics.json")
    shortcut = _j("shortcut_summary.json")
    summ = pd.read_csv(REPORTS_DIR / "model_comparison.csv")
    gen = pd.read_csv(REPORTS_DIR / "generalisation.csv")
    xd = pd.read_csv(REPORTS_DIR / "cross_dataset.csv")
    rob = pd.read_csv(REPORTS_DIR / "robustness.csv")
    out = []

    o = legacy["original_split"]
    out.append("### 1. The original result, reproduced and re-evaluated\n")
    out.append(_md(pd.DataFrame([
        {"Evaluation of the original pipeline": "Original single random split (accuracy)", "Score": f"{o['accuracy']:.3f}"},
        {"Evaluation of the original pipeline": "... majority-class guess on the same split", "Score": f"{o['majority_class_accuracy']:.3f}"},
        {"Evaluation of the original pipeline": "Group-aware 5-fold CV x3 (balanced accuracy)",
         "Score": _pm(legacy['group_cv_5fold_x3']['balanced_accuracy']['mean'], legacy['group_cv_5fold_x3']['balanced_accuracy']['std'])},
        {"Evaluation of the original pipeline": "Leave-one-source-speaker-out (balanced accuracy)",
         "Score": _pm(legacy['leave_one_source_out']['balanced_accuracy']['mean'], legacy['leave_one_source_out']['balanced_accuracy']['std'])},
    ])))
    out.append(f"\n{len(o['test_ai_files_with_same_source_recording_in_train'])} of the {o['n_test_ai']} AI test files in "
               "the original split had a re-voicing of the same source recording in the training set.\n")

    out.append("### 2. Model comparison (nested group-aware 5-fold CV, development partition, ROC-AUC mean ± std)\n")
    s = summ[(summ.augment == "none") & (summ.calibration == "default") & (summ.model != "majority")]
    rows = []
    for mdl in ["logreg", "linear_svm", "rbf_svm", "rbf_svm_original", "random_forest", "hist_gb"]:
        r = {"Model": LABELS[mdl]}
        for st in ("user", "user_codec_matched", "combined"):
            for fs in ("baseline", "extended"):
                x = s[(s.setting == st) & (s.feature_set == fs) & (s.model == mdl)]
                r[f"{ {'user': 'User', 'user_codec_matched': 'User codec-matched', 'combined': 'User+supp.'}[st]} / {fs}"] = (
                    _pm(x.roc_auc_mean.iloc[0], x.roc_auc_std.iloc[0]) if len(x) else "")
        rows.append(r)
    out.append(_md(pd.DataFrame(rows)))
    maj = summ[(summ.model == "majority")].roc_auc_mean.max()
    out.append(f"\nMajority-class baseline: ROC-AUC {maj:.3f} in every setting.\n")

    dep = sel["deploy"]
    best = sel["selection_by_setting"][dep["setting"]]["best_by_mean_auc"]
    tab = pd.DataFrame(sel["selection_by_setting"][dep["setting"]]["table"])
    runner = tab[~tab.tied_with_best].iloc[0] if (~tab.tied_with_best).any() else None
    udc = sel["user_domain_check"]
    out.append("### 3. Selected model\n")
    txt = (f"**{LABELS[dep['model']]} on {dep['feature_set']} features, trained on {SETTING_LABELS[dep['setting']]}** "
           f"(CV ROC-AUC {_pm(dep['roc_auc_mean'], dep['roc_auc_std'])}). It has the highest mean AUC in that setting "
           f"({LABELS[best['model']]} / {best['feature_set']})")
    tied = tab[tab.tied_with_best & ~((tab.model == best["model"]) & (tab.feature_set == best["feature_set"]))]
    txt += (", and no other candidate is statistically tied with it (paired group-bootstrap 95 % CI of the AUC "
            "difference excludes 0 for every alternative)" if tied.empty else
            f"; tied candidates: {', '.join(LABELS[m] + '/' + f for m, f in zip(tied.model, tied.feature_set))}")
    if runner is not None:
        txt += (f". Next best: {LABELS[runner.model]} / {runner.feature_set} ({runner.roc_auc_mean:.3f}; difference "
                f"{runner.auc_diff_best_minus_this:.3f}, 95 % CI {runner.ci_low:.3f} to {runner.ci_high:.3f})")
    txt += (f". Adding the supplementary data does not hurt on the user's own validation windows (out-of-fold AUC "
            f"{udc['oof_auc_on_user_rows_trained_combined']:.3f} vs {udc['oof_auc_on_user_rows_trained_user_only']:.3f} "
            f"user-only). First (pre-registered) augmentation rule, MP3 only: adopted {'yes' if aug['adopted'] else 'no'} "
            f"(clean CV AUC {aug['no_augmentation']['roc_auc_mean']:.3f} -> {aug['mp3_augmentation']['roc_auc_mean']:.3f}, "
            f"tolerance 0.005).")
    out.append(txt + "\n")
    rs_path = REPORTS_DIR / "selection" / "robustness_study.json"
    if rs_path.exists():
        rs = _j("selection/robustness_study.json")
        out.append("**Robustness study (development data only, run after the test-set robustness analysis of the "
                   "pre-registered model).** " + rs["rule"] + f" Chosen: `{rs['chosen']}`.\n")
        out.append(_md(pd.DataFrame([{"Training augmentation": r["candidate"],
                                      **{f"AUC {c}": f"{v:.3f}" for c, v in r["auc_by_condition"].items()},
                                      "Mean": f"{r['robust_auc']:.3f}"} for r in rs["candidates"]])))
        out.append("")
    out.append(f"**Deployed model:** {LABELS[meta['model_name']]} / {meta['feature_set']}, training augmentation "
               f"`{', '.join(meta['augmentation']) or 'none'}`, calibration {cal['chosen_method']}, threshold "
               f"{meta['threshold']:.2f} (false alarm cost 2, miss cost 1), inconclusive band "
               f"{meta['threshold'] - meta['inconclusive_halfwidth']:.2f}-{meta['threshold'] + meta['inconclusive_halfwidth']:.2f}; "
               f"development CV ROC-AUC of this configuration {cal['methods'][cal['chosen_method']]['roc_auc_mean']:.3f}.")
    dr = cal.get("dev_robustness_at_threshold", {})
    if dr:
        out.append("\nDevelopment-data robustness at the deployed threshold (validation windows perturbed):\n")
        out.append(_md(pd.DataFrame([{"Condition": c, "ROC-AUC": f"{v['roc_auc']:.3f}", "AI recall": f"{v['recall']:.3f}",
                                      "Human specificity": f"{v['specificity']:.3f}"} for c, v in dr.items()])))
    out.append("")

    out.append("### 4. Held-out test set\n")
    if "primary" in test:
        out.append("The **pre-registered** model (chosen before any test evaluation) is the primary result. The "
                   "**deployed** model was chosen afterwards by the development-data robustness study, so its test "
                   "numbers are post-hoc.\n")
    rows = []
    for tag, lab in (("deployed", "Deployed (post-hoc)" if "primary" in test else "Deployed"),
                     ("primary", "Pre-registered (primary)"), ("user_only", "User-only comparison")):
        if tag not in test:
            continue
        for scope, m in test[tag]["scopes"].items():
            ci = m.get("roc_auc_ci95")
            rows.append({"Model": lab, "Scope": scope, "Windows (AI/human)": f"{m['n']} ({m['n_ai']}/{m['n_human']})",
                         "ROC-AUC [95% CI]": (f"{m['roc_auc']:.3f} [{ci[0]:.3f}-{ci[1]:.3f}]" if ci else
                                              ("n/a" if pd.isna(m["roc_auc"]) else f"{m['roc_auc']:.3f}")),
                         "Balanced acc.": "n/a" if pd.isna(m["balanced_accuracy"]) else f"{m['balanced_accuracy']:.3f}",
                         "AI recall": f"{m['recall']:.3f}" if m["n_ai"] else "n/a",
                         "Human specificity": f"{m['specificity']:.3f}" if m["n_human"] else "n/a",
                         "F1": f"{m['f1']:.3f}" if m["n_ai"] else "n/a"})
    out.append(_md(pd.DataFrame(rows)))

    out.append("\n### 5. Generalisation (final configuration, fixed hyperparameters)\n")
    g = gen.groupby("experiment").agg(n=("held_out", "size"), recall=("recall_ai", "mean"), spec=("specificity_human", "mean"),
                                      auc=("roc_auc", "mean"), auc_sd=("roc_auc", "std")).reset_index()
    out.append(_md(pd.DataFrame({"Experiment": g.experiment, "Folds": g.n, "AI recall (mean)": g.recall.map("{:.3f}".format),
                                 "Human specificity (mean)": g.spec.map("{:.3f}".format),
                                 "ROC-AUC (mean ± std)": [_pm(a, b) for a, b in zip(g.auc, g.auc_sd)]})))
    uv = gen[gen.experiment.str.startswith("LOGO") & (gen.held_out == "user_vc")]
    if len(uv):
        r0 = uv.iloc[0]
        out.append(f"\nHolding out the **user's own voice-conversion generator** (training on all 19 ASVspoof systems "
                   f"and all human data instead): AI recall {r0.recall_ai:.3f}, ROC-AUC {r0.roc_auc:.3f} on the user's "
                   f"{int(r0.n_test_ai)} AI windows. A detector trained only on public data would not recognise this "
                   "generator.")
    out.append("\n" + _md(pd.DataFrame({"Cross-dataset": xd.experiment, "ROC-AUC": xd.roc_auc.map("{:.3f}".format),
                                         "Balanced acc.": xd.balanced_accuracy.map("{:.3f}".format),
                                         "AI recall": xd.recall_ai.map("{:.3f}".format),
                                         "Human specificity": xd.specificity_human.map("{:.3f}".format)})))

    out.append("\n### 6. Robustness (all test windows)\n")
    r = rob[rob.scope == "all test windows"].reset_index(drop=True)
    tab = pd.DataFrame({"Condition": r.description, "Balanced acc.": r.balanced_accuracy.map("{:.3f}".format),
                        "ROC-AUC": r.roc_auc.map("{:.3f}".format), "AI recall": r.recall_ai.map("{:.3f}".format),
                        "Human specificity": r.specificity_human.map("{:.3f}".format)})
    rp_path = REPORTS_DIR / "robustness_primary.csv"
    if rp_path.exists():
        rp = pd.read_csv(rp_path)
        rp = rp[rp.scope == "all test windows"].set_index("condition").reindex(r.condition)
        tab["Pre-registered: bal. acc."] = rp.balanced_accuracy.map("{:.3f}".format).values
        tab["Pre-registered: human spec."] = rp.specificity_human.map("{:.3f}".format).values
    out.append(_md(tab))

    out.append("\n### 7. Shortcut check (single-feature ROC-AUC within each data source, development data)\n")
    out.append(_md(pd.DataFrame([{"Data": k, "Best single feature": v["best_feature"],
                                  "Its ROC-AUC": f"{v['max_single_feature_auc']:.3f}",
                                  "Features with AUC >= 0.90": v["features_auc_ge_0.90"]} for k, v in shortcut.items()])))
    return "\n".join(out).strip() + "\n"


def data_markdown() -> str:
    audit = _j("dataset_audit.json")
    fsum = _j("feature_summary.json")
    names = {"user_commonvoice": "User: Mozilla Common Voice clips (`data/human`)",
             "user_voice_conversion": "User: voice conversions (`data/ai`)",
             "asvspoof2019_la": "Supplementary: ASVspoof 2019 LA subset (ODC-By)"}
    rows = []
    for src, v in audit["per_source"].items():
        rows.append({"Source": names.get(src, src), "Class": " + ".join(v["class"]), "Files": v["files"],
                     "Independent groups": v["groups"], "Group basis (confidence)": f"{v['group_basis']} ({v['group_confidence']})",
                     "Sample rates": ", ".join(f"{k} Hz" for k in v["sample_rates"]),
                     "Analysis windows": v["windows_total"], "Skipped by loader": len(v["rejected_by_loader"])})
    ad = audit["adequacy"]["user_only"]
    failed = [k.replace("_", " ") for k, ok in ad["checks"].items() if not ok]
    return (_md(pd.DataFrame(rows)) + f"\n\nTotal: {audit['files_total']} files, {fsum['windows_orig']} analysis windows. "
            f"User data alone fails these adequacy checks: {'; '.join(failed)}.\n")


def _replace(text: str, start: str, end: str, body: str) -> str:
    if start not in text or end not in text:
        raise ValueError(f"README.md is missing the marker {start[:20]}...")
    pre, rest = text.split(start, 1)
    _, post = rest.split(end, 1)
    return pre + start + "\n" + body + end + post


def update_readme() -> bool:
    p = ROOT / "README.md"
    text = p.read_text(encoding="utf-8")
    new = _replace(text, DATA_START, DATA_END, data_markdown())
    new = _replace(new, RESULTS_START, RESULTS_END, results_markdown())
    p.write_text(new, encoding="utf-8")
    return new != text


def _block(start: str, end: str) -> str:
    text = (ROOT / "README.md").read_text(encoding="utf-8")
    return text.split(start, 1)[1].split(end, 1)[0].lstrip("\n")


def readme_block() -> str:
    return _block(RESULTS_START, RESULTS_END)


def readme_data_block() -> str:
    return _block(DATA_START, DATA_END)
